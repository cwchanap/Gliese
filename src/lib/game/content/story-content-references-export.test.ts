import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import {
	collectStoryContentReferences,
	normalizeStoryContentReferences,
	renderStoryContentReferences,
	runStoryContentReferenceExporter,
	syncGeneratedStoryContentReferences,
	type StoryContentReferences
} from '../../../../tools/export-story-content-references';

const temporaryRoots: string[] = [];
const FIXTURE: StoryContentReferences = {
	questIds: ['quest-z', 'quest-a'],
	objectiveIds: ['objective-z', 'objective-a'],
	shopIds: ['shop-z', 'shop-a'],
	sceneIds: ['scene.z', 'scene.a', 'scene.z'],
	npcPlacements: [
		['z-map', 'npc-z'],
		['a-map', 'npc-a']
	]
};

afterEach(() => {
	for (const root of temporaryRoots.splice(0)) rmSync(root, { recursive: true, force: true });
});

describe('story content reference generation', () => {
	it('renders sorted deterministic Rust with a generated header', () => {
		const source = renderStoryContentReferences(FIXTURE);
		expect(source).toMatch(
			/^\/\/ @generated by tools\/export-story-content-references\.ts\. Do not edit by hand\./
		);
		expect(source.indexOf('"quest-a"')).toBeLessThan(source.indexOf('"quest-z"'));
		expect(source.indexOf('("a-map", "npc-a")')).toBeLessThan(source.indexOf('("z-map", "npc-z")'));
		expect(source).toContain('pub const NPC_PLACEMENTS: &[(&str, &str)] = &[');
		expect(source.endsWith('\n')).toBe(true);
		expect(renderStoryContentReferences(FIXTURE)).toBe(source);
	});

	it('renders short ID lists in rustfmt-compatible form', () => {
		const source = renderStoryContentReferences(FIXTURE);
		expect(source).toContain('pub const SHOP_IDS: &[&str] = &["shop-a", "shop-z"];');
		expect(source).toContain('pub const SCENE_IDS: &[&str] = &["scene.a", "scene.z"];');
	});

	it('escapes Rust string literals', () => {
		const source = renderStoryContentReferences({
			...FIXTURE,
			npcPlacements: [['map\\path', 'npc"quoted']]
		});
		expect(source).toContain('"map\\\\path"');
		expect(source).toContain('"npc\\"quoted"');
	});

	it('rejects duplicate IDs and placements', () => {
		expect(() =>
			normalizeStoryContentReferences({ ...FIXTURE, questIds: ['same', 'same'] })
		).toThrow(/duplicate quest id same/);
		expect(() =>
			normalizeStoryContentReferences({ ...FIXTURE, objectiveIds: ['same', 'same'] })
		).toThrow(/duplicate objective id same/);
		expect(() =>
			normalizeStoryContentReferences({
				...FIXTURE,
				npcPlacements: [
					['guild-hall', 'borak'],
					['guild-hall', 'borak']
				]
			})
		).toThrow(/duplicate npc placement guild-hall\/borak/);
	});

	it('rejects a dialogue id placed on multiple maps', () => {
		expect(() =>
			normalizeStoryContentReferences({
				...FIXTURE,
				npcPlacements: [
					['guild-hall', 'borak'],
					['overworld', 'borak']
				]
			})
		).toThrow(
			/npc borak is placed on multiple maps .* the runtime model requires exactly one map per npc/
		);
	});

	it('checks exact bytes without writing missing or stale output', () => {
		const root = mkdtempSync(join(tmpdir(), 'gliese-story-references-'));
		temporaryRoots.push(root);
		const destination = join(root, 'reference.rs');
		const source = renderStoryContentReferences(FIXTURE);

		expect(() => syncGeneratedStoryContentReferences(source, destination, true)).toThrow(
			/generated story references are missing/
		);
		writeFileSync(destination, 'stale\n');
		expect(() => syncGeneratedStoryContentReferences(source, destination, true)).toThrow(
			/generated story references are stale/
		);
		expect(readFileSync(destination, 'utf8')).toBe('stale\n');
	});

	it('publishes complete output and passes exact-byte check mode', () => {
		const root = mkdtempSync(join(tmpdir(), 'gliese-story-references-'));
		temporaryRoots.push(root);
		const destination = join(root, 'nested', 'reference.rs');
		const source = renderStoryContentReferences(FIXTURE);

		syncGeneratedStoryContentReferences(source, destination, false);
		expect(readFileSync(destination, 'utf8')).toBe(source);
		expect(() => syncGeneratedStoryContentReferences(source, destination, true)).not.toThrow();
	});

	it('does not replace an existing destination when validation fails', () => {
		const root = mkdtempSync(join(tmpdir(), 'gliese-story-references-'));
		temporaryRoots.push(root);
		const destination = join(root, 'reference.rs');
		writeFileSync(destination, 'previous\n');

		expect(() => renderStoryContentReferences({ ...FIXTURE, shopIds: ['same', 'same'] })).toThrow(
			/duplicate shop id same/
		);
		expect(readFileSync(destination, 'utf8')).toBe('previous\n');
	});

	it('collects the current authoritative registries', () => {
		const references = collectStoryContentReferences();
		expect(references.questIds).toContain('prologue-proving-morning');
		expect(references.objectiveIds).toContain('report-to-borak');
		expect(references.shopIds).toContain('miras-item-shop');
		// Quest effects and story discoveries both contribute scenes.
		expect(references.sceneIds).toContain('prologue.opening');
		expect(references.sceneIds).toContain('prologue.boar-sign-sapling');
		expect(references.npcPlacements).toContainEqual(['guild-hall', 'borak']);
		expect(references.npcPlacements).toContainEqual(['overworld', 'lirra-forest']);
	});

	it('writes current references through the zero-argument CLI', () => {
		const root = mkdtempSync(join(tmpdir(), 'gliese-story-references-'));
		temporaryRoots.push(root);
		const destination = join(root, 'src-tauri', 'src', 'story', 'reference.rs');

		runStoryContentReferenceExporter([], root);

		const output = readFileSync(destination, 'utf8');
		expect(output).toContain(
			'// @generated by tools/export-story-content-references.ts. Do not edit by hand.'
		);
		expect(output).toContain('("guild-hall", "borak")');
	});

	it('checks generated references through the check CLI mode', () => {
		const root = mkdtempSync(join(tmpdir(), 'gliese-story-references-'));
		temporaryRoots.push(root);

		runStoryContentReferenceExporter([], root);

		expect(() => runStoryContentReferenceExporter(['--check'], root)).not.toThrow();
	});

	it('rejects unexpected exporter arguments', () => {
		expect(() => runStoryContentReferenceExporter(['--write'])).toThrow(
			'Usage: bun tools/export-story-content-references.ts [--check]'
		);
	});
});
