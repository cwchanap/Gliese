use super::types::{
    NpcStoryDialogue, StoryBranchCondition, StoryCatalog, StoryDialogueAction, StoryDialogueBranch,
    StoryIntent, StoryLine, StoryScene,
};

pub fn generate_story_catalog_source(catalog: &StoryCatalog) -> String {
    let mut source = String::new();
    source.push_str("// @generated by story_check. Do not edit by hand.\n\n");
    source.push_str("#[allow(unused_imports)]\n");
    source.push_str("use super::types::{\n");
    source.push_str(
        "    NpcStoryDialogue, StoryBranchCondition, StoryCatalog, StoryDialogueAction, StoryDialogueBranch,\n",
    );
    source.push_str("    StoryIntent, StoryLine, StoryScene,\n");
    source.push_str("};\n\n");
    source.push_str("pub fn story_catalog() -> StoryCatalog {\n");
    source.push_str("    StoryCatalog {\n");
    push_string_field(&mut source, 8, "package_id", &catalog.package_id);
    push_string_field(&mut source, 8, "default_locale", &catalog.default_locale);
    source.push_str("        npc_dialogues: vec![\n");
    for dialogue in &catalog.npc_dialogues {
        push_npc_dialogue(&mut source, dialogue, 12);
    }
    source.push_str("        ],\n");
    source.push_str("        scenes: vec![\n");
    for scene in &catalog.scenes {
        push_scene(&mut source, scene, 12);
    }
    source.push_str("        ],\n");
    source.push_str("    }\n");
    source.push_str("}\n");
    source
}

/// The same catalog as JSON for the browser-only dev fixture. Release builds
/// never import it (see `tools/assert-no-frontend-story-prose.ts`).
pub fn generate_browser_catalog_json(catalog: &StoryCatalog) -> String {
    let mut json = serde_json::to_string_pretty(catalog).expect("story catalog serializes");
    json.push('\n');
    json
}

fn push_npc_dialogue(source: &mut String, dialogue: &NpcStoryDialogue, indent: usize) {
    push_indent(source, indent);
    source.push_str("NpcStoryDialogue {\n");
    push_string_field(source, indent + 4, "npc_id", &dialogue.npc_id);
    push_string_field(source, indent + 4, "map_id", &dialogue.map_id);
    push_indent(source, indent + 4);
    source.push_str("branches: vec![\n");
    for branch in &dialogue.branches {
        push_dialogue_branch(source, branch, indent + 8);
    }
    push_indent(source, indent + 4);
    source.push_str("],\n");
    push_indent(source, indent);
    source.push_str("},\n");
}

fn push_dialogue_branch(source: &mut String, branch: &StoryDialogueBranch, indent: usize) {
    push_indent(source, indent);
    source.push_str("StoryDialogueBranch {\n");
    push_string_field(source, indent + 4, "beat_id", &branch.beat_id);
    push_indent(source, indent + 4);
    source.push_str("condition: ");
    push_branch_condition(source, &branch.condition);
    source.push_str(",\n");
    push_lines(source, &branch.lines, indent + 4);
    push_indent(source, indent + 4);
    source.push_str("actions: vec![\n");
    for action in &branch.actions {
        push_dialogue_action(source, action, indent + 8);
    }
    push_indent(source, indent + 4);
    source.push_str("],\n");
    push_indent(source, indent);
    source.push_str("},\n");
}

fn push_scene(source: &mut String, scene: &StoryScene, indent: usize) {
    push_indent(source, indent);
    source.push_str("StoryScene {\n");
    push_string_field(source, indent + 4, "id", &scene.id);
    push_string_field(source, indent + 4, "beat_id", &scene.beat_id);
    push_lines(source, &scene.lines, indent + 4);
    push_indent(source, indent);
    source.push_str("},\n");
}

fn push_lines(source: &mut String, lines: &[StoryLine], indent: usize) {
    push_indent(source, indent);
    source.push_str("lines: vec![\n");
    for line in lines {
        push_indent(source, indent + 4);
        source.push_str("StoryLine {\n");
        push_string_field(source, indent + 8, "speaker", &line.speaker);
        push_string_field(source, indent + 8, "text", &line.text);
        push_indent(source, indent + 4);
        source.push_str("},\n");
    }
    push_indent(source, indent);
    source.push_str("],\n");
}

fn push_dialogue_action(source: &mut String, action: &StoryDialogueAction, indent: usize) {
    push_indent(source, indent);
    source.push_str("StoryDialogueAction {\n");
    push_string_field(source, indent + 4, "id", &action.id);
    push_string_field(source, indent + 4, "label", &action.label);
    push_indent(source, indent + 4);
    source.push_str("intent: ");
    push_story_intent(source, &action.intent, indent + 4);
    source.push_str(",\n");
    push_indent(source, indent);
    source.push_str("},\n");
}

fn push_story_intent(source: &mut String, intent: &StoryIntent, indent: usize) {
    match intent {
        StoryIntent::OpenShop { shop_id } => {
            source.push_str("StoryIntent::OpenShop {\n");
            push_indent(source, indent + 4);
            source.push_str("shop_id: ");
            push_rust_string(source, shop_id);
            source.push_str(".to_string(),\n");
            push_indent(source, indent);
            source.push('}');
        }
        StoryIntent::Close => source.push_str("StoryIntent::Close"),
    }
}

fn push_branch_condition(source: &mut String, condition: &StoryBranchCondition) {
    match condition {
        StoryBranchCondition::Always => source.push_str("StoryBranchCondition::Always"),
        StoryBranchCondition::Quest(id) => {
            source.push_str("StoryBranchCondition::Quest(");
            push_rust_string(source, id);
            source.push_str(".to_string())");
        }
        StoryBranchCondition::Objective(id) => {
            source.push_str("StoryBranchCondition::Objective(");
            push_rust_string(source, id);
            source.push_str(".to_string())");
        }
    }
}

fn push_string_field(source: &mut String, indent: usize, field: &str, value: &str) {
    push_indent(source, indent);
    source.push_str(field);
    source.push_str(": ");
    push_rust_string(source, value);
    source.push_str(".to_string(),\n");
}

fn push_rust_string(source: &mut String, value: &str) {
    source.push('"');
    for character in value.chars() {
        match character {
            '\\' => source.push_str("\\\\"),
            '"' => source.push_str("\\\""),
            '\n' => source.push_str("\\n"),
            '\r' => source.push_str("\\r"),
            '\t' => source.push_str("\\t"),
            _ => source.push(character),
        }
    }
    source.push('"');
}

fn push_indent(source: &mut String, indent: usize) {
    for _ in 0..indent {
        source.push(' ');
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_catalog() -> StoryCatalog {
        StoryCatalog {
            package_id: "gliese".to_string(),
            default_locale: "en".to_string(),
            npc_dialogues: vec![NpcStoryDialogue {
                npc_id: "mira".to_string(),
                map_id: "item-shop".to_string(),
                branches: vec![StoryDialogueBranch {
                    beat_id: "prologue.morning".to_string(),
                    condition: StoryBranchCondition::Objective("collect-herbs".to_string()),
                    lines: vec![StoryLine {
                        speaker: "Mira".to_string(),
                        text: "Say \"thank you\".".to_string(),
                    }],
                    actions: vec![StoryDialogueAction {
                        id: "shop".to_string(),
                        label: "Shop".to_string(),
                        intent: StoryIntent::OpenShop {
                            shop_id: "herb-hut".to_string(),
                        },
                    }],
                }],
            }],
            scenes: vec![StoryScene {
                id: "scene.opening".to_string(),
                beat_id: "prologue.morning".to_string(),
                lines: vec![StoryLine {
                    speaker: String::new(),
                    text: "Dawn.".to_string(),
                }],
            }],
        }
    }

    #[test]
    fn emits_rust_field_names_conditions_and_escaped_strings() {
        let source = generate_story_catalog_source(&sample_catalog());

        assert!(source.contains("// @generated by story_check. Do not edit by hand."));
        assert!(source.contains(
            "condition: StoryBranchCondition::Objective(\"collect-herbs\".to_string()),"
        ));
        assert!(source.contains("shop_id: \"herb-hut\".to_string(),"));
        assert!(source.contains("text: \"Say \\\"thank you\\\".\".to_string(),"));
        assert!(source.contains("id: \"scene.opening\".to_string(),"));
        assert!(!source.contains("shopId"));
    }

    #[test]
    fn browser_json_round_trips_the_catalog() {
        let catalog = sample_catalog();
        let json = generate_browser_catalog_json(&catalog);

        assert!(json.ends_with('\n'));
        let parsed: StoryCatalog = serde_json::from_str(&json).expect("json parses");
        assert_eq!(parsed, catalog);
    }
}
